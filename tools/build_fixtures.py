"""Convert the fixture PDFs in the project root into assets/js/data.js.
Run from the project root:  python tools/build_fixtures.py   (needs: pip install pypdf)
"""
import glob, json, re, datetime, os
import pypdf

SOURCES = {
    "A Grade 2026 semsa.pdf":  ("SEMSA Summer", "A Grade"),
    "B1 Grade 2026 semsa.pdf": ("SEMSA Summer", "B1 Grade"),
    "B4 Grade 2026 semsa.pdf": ("SEMSA Summer", "B4 Grade"),
    "C2 Grade 2026 semsa.pdf": ("SEMSA Summer", "C2 Grade"),
    "State Legue.pdf":         ("State League", "Qbit State League"),
}
DAY = re.compile(r"^(Mon|Tue|Wed|Thu|Fri|Sat|Sun) (\d\d) (\w{3}) (\d{4})$")
ROUND = re.compile(r"^Round (\d+) · Week starting")
NOISE = re.compile(r"^(Page \d+ of \d+|Accessed .*)$")
BYE = re.compile(r"^(.*) have a BYE\.$")
TIME = re.compile(r"^\d\d:\d\d$")
CLUB = re.compile(r"Rebels|Mariners")

fixtures, teams = [], {}
for pdf, (category, grade) in SOURCES.items():
    lines = []
    for page in pypdf.PdfReader(pdf).pages:
        lines += [l.strip() for l in page.extract_text().splitlines() if l.strip()]
    lines = [l for l in lines if not NOISE.match(l)]
    rnd, venue, i = None, "", 0
    while i < len(lines):
        l = lines[i]
        m = ROUND.match(l)
        if m:
            rnd, venue = int(m.group(1)), lines[i + 1]
            i += 2
            continue
        m = DAY.match(l)
        if m and rnd:
            date = datetime.datetime.strptime(" ".join(m.groups()[1:]), "%d %b %Y").date()
            time, sub, home, away = lines[i + 1], lines[i + 2], lines[i + 3], lines[i + 4]
            assert TIME.match(time), (pdf, lines[i:i + 5])
            fixtures.append(dict(category=category, grade=grade, round=rnd, date=date.isoformat(),
                                 time=time, venue=venue, field=sub, home=home, away=away,
                                 homeScore=None, awayScore=None))
            teams.setdefault((category, grade), set()).update([home, away])
            i += 5
            continue
        m = BYE.match(l)
        if m:
            teams.setdefault((category, grade), set()).add(m.group(1))
        i += 1

fixtures.sort(key=lambda f: (f["date"], f["time"]))
for n, f in enumerate(fixtures, 1):
    f["id"] = n

comps = [{"category": c, "grade": g, "teams": sorted(t),
          "clubTeams": sorted(x for x in t if CLUB.search(x))} for (c, g), t in teams.items()]

out = ("// Generated by tools/build_fixtures.py from the PDFs in the project root.\n"
       "// Add scores by setting homeScore / awayScore on a fixture to turn it into a result.\n"
       "window.REBELS_DATA = " + json.dumps({"competitions": comps, "fixtures": fixtures}, indent=1) + ";\n")
os.makedirs("assets/js", exist_ok=True)
open("assets/js/data.js", "w", encoding="utf-8").write(out)
print(len(fixtures), "fixtures;", sum(1 for f in fixtures if CLUB.search(f["home"] + f["away"])), "involve the club")
for c in comps:
    print(c["grade"], c["clubTeams"], len(c["teams"]))
